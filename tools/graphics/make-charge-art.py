#!/usr/bin/env python3
"""Generate offline-charge-art.h from Reborn's charging layout.

The rescue-environment charger (tools/production/offline-charge.c) draws the
screen shown while the player is off and charging. Every static image (ring
track and bolt, title and hint lines) is rendered from Reborn's own quads by
Reborn's preview rasterizer, as RGB888 runs over the region that differs from
the background; the charger only adds the ring's sweeping segment itself.

Input is `charge-layout.json`, written by Y2Reborn's `reborn-preview`
(docs/ui/previews/v3/charge-layout.json).

Usage: make-charge-art.py CHARGE_LAYOUT.json OUTPUT.h [--reborn REBORN_ROOT]
"""
import argparse
import importlib.util
import json
from pathlib import Path

from PIL import Image


def load_rasterizer(reborn):
    spec = importlib.util.spec_from_file_location('render_previews', reborn / 'tools/preview/render_previews.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.Rasterizer(reborn)


def encode(image, background):
    pixels = image.load()
    box = None
    for y in range(image.height):
        for x in range(image.width):
            if pixels[x, y] != background:
                box = (min(box[0], x), min(box[1], y), max(box[2], x), max(box[3], y)) if box else (x, y, x, y)
    if box is None:
        raise SystemExit('image is empty')
    left, top, right, bottom = box
    runs, previous, count = [], None, 0
    for y in range(top, bottom + 1):
        for x in range(left, right + 1):
            colour = pixels[x, y]
            if colour == previous and count < 255:
                count += 1
            else:
                if previous is not None:
                    runs.append((count, *previous))
                previous, count = colour, 1
    runs.append((count, *previous))
    return {'x': left, 'y': top, 'w': right - left + 1, 'h': bottom - top + 1,
            'data': [value for run in runs for value in run]}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('layout', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--reborn', type=Path)
    args = parser.parse_args()
    layout = json.loads(args.layout.read_text())
    if layout.get('schema') != 'org.reborn.charge-layout/v1' or (layout['width'], layout['height']) != (480, 360):
        raise SystemExit('unsupported charge layout')
    reborn = (args.reborn or args.layout.resolve().parents[4]).resolve()
    raster = load_rasterizer(reborn)
    value = layout['background']
    background = (value >> 16 & 255, value >> 8 & 255, value & 255)

    def render(quads):
        return raster.render(quads, background + (255,))

    images = [encode(render(layout['base']), background)]
    for key in ('titles', 'hints'):
        for entry in layout[key]:
            images.append(encode(render(entry['quads']), background))
    blob, offsets = [], []
    for image in images:
        offsets.append(len(blob))
        blob.extend(image['data'])
    lines = [', '.join(f'0x{v:02x}' for v in blob[i:i + 16]) for i in range(0, len(blob), 16)]
    rows = ',\n'.join(f'    {{{i["x"]}u, {i["y"]}u, {i["w"]}u, {i["h"]}u, {o}u, {len(i["data"])}u}}'
                      for i, o in zip(images, offsets))
    ring = layout['ring']
    rgb = lambda v: f'0x{v:06x}u'
    args.output.write_text(
        "/* Generated by tools/graphics/make-charge-art.py from Reborn's charging layout.\n"
        ' * Images are RGB888 runs (count, red, green, blue) rendered by Reborn itself.\n'
        ' * Do not edit by hand. */\n'
        '#ifndef OFFLINE_CHARGE_ART_H\n#define OFFLINE_CHARGE_ART_H\n'
        f'#define CHG_BG {rgb(layout["background"])}\n'
        f'#define CHG_TRACK {rgb(ring["track"])}\n#define CHG_LIT {rgb(ring["lit"])}\n'
        f'#define CHG_CX {float(ring["cx"])}f\n#define CHG_CY {float(ring["cy"])}f\n'
        f'#define CHG_OUTER {float(ring["outer"])}f\n#define CHG_INNER {float(ring["inner"])}f\n'
        'typedef struct { unsigned short x, y, w, h; unsigned offset, length; } chg_image;\n'
        'static const unsigned char chg_art_rle[] = {\n    ' + ',\n    '.join(lines) + '\n};\n'
        'static const chg_image chg_images[] = {\n' + rows + '\n};\n'
        '/* 0 base; 1..3 titles (Charging, Charged, Charging paused); 4..6 hints\n'
        ' * (Hold Power to turn on, Release to start, Battery too low to start). */\n'
        '#define CHG_BASE 0u\n#define CHG_TITLE(n) (1u + (n))\n#define CHG_HINT(n) (4u + (n))\n'
        '#endif\n')
    print(f'{args.output}: {len(images)} images, {len(blob)} bytes of art')


if __name__ == '__main__':
    main()
